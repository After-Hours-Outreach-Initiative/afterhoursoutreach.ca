/** Event, access, approval and role messages all use this delivery footer. */
export function eventNotificationEmail(
  content: EmailContent,
  origin: string,
): EmailContent {
  return { ...content, text: `${content.text}\n\nEvents: ${origin}/events` };
}

export function medicCertificationEmail(
  kind: "warning" | "expired",
  expiry: string,
  origin: string,
): EmailContent {
  const warning = kind === "warning";
  return {
    subject: warning
      ? "Your medic certification is expiring soon"
      : "Your medic certification has expired",
    text: `${
      warning
        ? `Your volunteer profile lists a medic certification expiry date of ${expiry}, within the next 30 days. It remains valid through that date. Please arrange renewal.`
        : `The medic certification expiry date on your volunteer profile was ${expiry}. It is now expired. Please renew before volunteering as a medic.`
    }
\nIf you have renewed or this date is incorrect, update the certification expiry date in your account: ${origin}/volunteer/account`,
  };
}
