export interface EmailEvent {
  type: "patrol" | "orientation";
  includesOrientation?: number;
  startsAt: number;
  meetingPoint: string;
}

export function eventDescription(event: EmailEvent) {
  return `Patrol${(event.includesOrientation ?? event.type === "orientation") ? " (includes orientation)" : ""}: ${new Intl.DateTimeFormat(
    "en-CA",
    {
      timeZone: "America/Vancouver",
      dateStyle: "full",
      timeStyle: "short",
    },
  ).format(new Date(event.startsAt))}\nMeeting point: ${event.meetingPoint}`;
}

export function eventChangedEmail(
  event: EmailEvent,
  open: boolean,
): EmailContent {
  return {
    subject: "Your event changed",
    text: `${eventDescription(event)}\n\n${open ? "Registration is open." : "Registration is closed. Your existing spot is still reserved."}`,
  };
}

export function eventCancelledEmail(
  event: EmailEvent,
  reason: string,
): EmailContent {
  return {
    subject: "Your event was cancelled",
    text: `${eventDescription(event)}\n\nThis event was cancelled.${reason ? `\nReason: ${reason}` : ""}`,
  };
}

export function registrationChangedEmail(
  previous: EmailEvent,
  next: EmailEvent | null,
  reason: string,
): EmailContent {
  return {
    subject: next
      ? "Your event registration was moved"
      : "Your event registration was removed",
    text: `${eventDescription(previous)}\n\n${next ? `An organizer moved your registration to:\n${eventDescription(next)}` : "An organizer removed your registration."}${reason ? `\nReason: ${reason}` : ""}`,
  };
}

