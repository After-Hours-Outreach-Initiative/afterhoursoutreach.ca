export function signInEmailContent(email: SignInEmailInput): EmailContent {
  if (email.purpose === "change-email")
    return {
      subject: "Confirm your email change",
      text: `Enter this code in your account settings to confirm your new email address: ${email.code}\n\nThe code expires in ten minutes and can only be used once. Requesting a new code for this address replaces the previous code. Your email address will not change until you confirm it.\n\nIf you did not request this, ignore this email.`,
    };
  return {
    subject: `${email.code} is your sign-in code`,
    text: `Sign in: ${email.url}\n\nOr enter this code on the device that requested it: ${email.code}\n\n${signInExpiry}\n\n${signInSecurity}`,
    html: signInHtml(email),
  };
}

// These two messages are composed inside atomic SQL writes. Sharing their text
// templates keeps previews accurate without moving transactional reads into JS.
export const applicationSubmittedTemplate = {
  subject: "New volunteer application submitted",
  text: "Applicant: {{applicant}}\nSubmitted: {{submittedAt}}\nOrganizer review (authorized organizer sign-in required): {{reviewUrl}}",
} satisfies EmailContent;

export const accessRegistrationCancelledTemplate = {
  subject: "Your event registration was cancelled",
  text: "Your registration for a patrol{{orientation}} at {{meetingPoint}} was cancelled because your volunteer access changed. Check Your account or contact an organizer.",
} satisfies EmailContent;

export function renderEmailText(
  template: string,
  values: Record<string, string>,
) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    if (!Object.hasOwn(values, key))
      throw new Error(`Missing email template value: ${key}`);
    return values[key];
  });
}

export function applicationSubmittedEmail(values: {
  applicant: string;
  submittedAt: string;
  reviewUrl: string;
}): EmailContent {
  return {
    subject: applicationSubmittedTemplate.subject,
    text: renderEmailText(applicationSubmittedTemplate.text, {
      ...values,
      applicant: values.applicant.replaceAll("\r", " ").replaceAll("\n", " "),
    }),
  };
}

export function accessRegistrationCancelledEmail(
  meetingPoint: string,
  includesOrientation: boolean,
): EmailContent {
  return {
    subject: accessRegistrationCancelledTemplate.subject,
    text: renderEmailText(accessRegistrationCancelledTemplate.text, {
      orientation: includesOrientation ? " (includes orientation)" : "",
      meetingPoint,
    }),
  };
}

interface VolunteerAccess {
  active: boolean;
  applicationApproved: boolean;
  patrolApproved: boolean;
}

export function volunteerAccessEmail(
  { active, applicationApproved, patrolApproved }: VolunteerAccess,
  applicationApprovalChanged: boolean,
): EmailContent {
  const nextStep = !active
    ? `Your volunteer account is currently inactive. Please contact an organizer at ${contactEmail} to restore access before registering for events.`
    : !applicationApproved
      ? "Sign in using the events link below to review your application steps on the Volunteer page."
      : patrolApproved
        ? "Sign in using the events link below to browse upcoming patrols and register for an available spot."
        : 'Sign in using the events link below. If Naloxone 101 completion is not yet confirmed, return to the Volunteer page, complete the course if needed, and confirm completion only after finishing it. Once completion is confirmed, choose an "Orientation + Patrol" event to register for an available spot. You’ll need separate organizer approval for patrols without orientation.';
  if (!applicationApprovalChanged)
    return {
      subject: "Your volunteer access changed",
      text: `Volunteer account: ${active ? "active" : "inactive"}. Application: ${applicationApproved ? "approved" : "awaiting organizer approval"}. Patrol access: ${patrolApproved ? "approved" : "not approved"}. ${nextStep} Orientation attendance does not automatically grant patrol approval.`,
    };
  if (!applicationApproved)
    return {
      subject: "Your volunteer application approval was revoked",
      text: `Your volunteer application is awaiting organizer approval again. ${nextStep} Check Your account for any changes to your registrations, or contact an organizer if you have questions.`,
    };
  return {
    subject: "Your volunteer application is approved",
    text: `Your volunteer application is approved! Thanks for joining us and supporting our community.\n\n${nextStep}`,
  };
}

