import { RequestError } from "../http";
import { emailPolicy } from "../db/policy";

export interface SignInEmail {
  email: string;
  code: string;
  url: string;
  id: string;
  purpose?: "change-email";
}

const signInExpiry = "The link and code expire in 10 minutes.";
const signInSecurity =
  "If you did not request this, you can safely ignore this email.";

function escapeHtml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function signInHtml(email: SignInEmail) {
  // The URL is generated by auth. Escape for HTML without changing its fragment.
  const url = escapeHtml(email.url);
  return `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Your After Hours Outreach sign-in</title></head>
<body style="margin:0;padding:0;background-color:#ffffff;">
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
    <tr><td align="center">
      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width:680px;table-layout:fixed;">
        <tr><td bgcolor="#ffffff" style="padding:24px 40px 32px;font-family:Arial,Helvetica,sans-serif;font-size:13px;line-height:20px;color:#000000;">
          <h1 style="margin:0 0 14px;font-size:20px;line-height:28px;font-weight:600;">Sign in to After Hours Outreach</h1>
          <p style="margin:0 0 22px;">Enter this code on the sign-in page, or click the sign-in link.</p>
          <p style="margin:0 0 12px;padding:8px 16px;border:1px solid #e7e7e7;border-radius:8px;background-color:#f7f7f7;font-family:monospace;font-size:24px;font-weight:normal;line-height:32px;text-align:center;">${escapeHtml(email.code)}</p>
          <p style="margin:0 0 12px;text-align:center;">OR</p>
          <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
            <tr><td align="center" bgcolor="#4169e1" style="border-radius:8px;"><a href="${url}" style="display:block;padding:13px 20px;border-radius:8px;background-color:#4169e1;color:#ffffff;font-size:16px;font-weight:bold;line-height:24px;text-align:center;text-decoration:none;">Sign in</a></td></tr>
          </table>
          <p style="margin:28px 0 8px;">${signInExpiry}</p>
          <p style="margin:0 0 24px;">${signInSecurity}</p>
        </td></tr>
      </table>
    </td></tr>
  </table>
</body>
</html>`;
}

export async function sendSignInEmail(
  key: string | undefined,
  email: SignInEmail,
  environment: string,
  fetcher: typeof fetch = fetch,
) {
  // A dev server must never contact the email provider, even with a real key
  // or an accidentally selected remote environment. No shared local outbox.
  if (import.meta.env?.DEV || environment === "local") return email;
  if (!key) throw new RequestError(503, "Sign-in email is not configured yet.");
  const response = await fetcher("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${key}`,
      "Content-Type": "application/json",
      "Idempotency-Key": `sign-in/${email.id}`,
    },
    signal: AbortSignal.timeout(emailPolicy.timeoutMs),
    body: JSON.stringify({
      from: "After Hours Outreach <noreply@afterhoursoutreach.ca>",
      to: [email.email],
      subject:
        email.purpose === "change-email"
          ? "Confirm your After Hours Outreach email change"
          : `${email.code} is your After Hours Outreach sign-in code`,
      text:
        email.purpose === "change-email"
          ? `Enter this code in your account settings to confirm your new email address: ${email.code}\n\nThe code expires in ten minutes and can only be used once. Requesting a new code for this address replaces the previous code. Your email address will not change until you confirm it.\n\nIf you did not request this, ignore this email.`
          : `Sign in: ${email.url}\n\nOr enter this code on the device that requested it: ${email.code}\n\n${signInExpiry}\n\n${signInSecurity}`,
      ...(email.purpose !== "change-email" && { html: signInHtml(email) }),
    }),
  });
  // Provider bodies can contain recipient details; never expose or log them.
  if (!response.ok)
    throw new RequestError(
      503,
      "We could not send the email. Try again later.",
    );
  await response.body?.cancel();
}
